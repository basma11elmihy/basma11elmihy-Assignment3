    // Solve LeetCode 136 — Single Number:
    // Example
    //Input: nums = [4, 1, 2, 1, 2]
    //Output: 4
    private static int FindSingleNumber(int[] nums)
    {
        int result = 0;

        for (int i = 0; i < nums.Length; i++)
        {
            result ^= nums[i]; // XOR operation
        }
        return result;
    }
