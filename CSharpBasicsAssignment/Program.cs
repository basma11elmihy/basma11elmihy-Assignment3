    struct Point
    {
        public int X;
        public int Y;
    }

    private static void RunValueVsReferenceDemo()
    {
        // Experiment #1: Value Type (Struct) Assignment
        Point p1 = new Point { X = 1, Y = 2 };
        Point p2 = p1; // Value type assignment, creates a copy
        p2.X = 99;

        // Changing p2 does not affect p1 because structs are value types
        // and assigning one struct to another creates an independent copy.
        Console.WriteLine($"p1.X: {p1.X}, p2.X: {p2.X}");


        // Experiment #2: Reference Type (Class) Assignment
        Order o1 = new Order
        {
            OrderId = 101,
            CustomerName = "Basma",
            Quantity = 3,
            UnitPrice = 100m,
            TotalPrice = 0m,
            IsPaid = false,
            DiscountPercent = 10.0,
            ShippingCity = "Cairo",
            Priority = 'H',
            ItemCode = 123456789L
        };

        o1.CalculateTotal();

        Order o2 = o1;
        o2.IsPaid = true;
        Console.WriteLine($"o1.IsPaid: {o1.IsPaid}, o2.IsPaid: {o2.IsPaid}");
        // Reference type assignment, both o1 and o2 refer to the same object SO CHANGING o2 WILL CHANGE o1

        object boxedOrder = o1; // Boxing the reference type
        Order o3 = (Order)boxedOrder;

        Console.WriteLine($"o1.IsPaid: {o1.IsPaid}, o3.IsPaid: {o3.IsPaid}");

        o2.PrintSummary();

    }

